// Regenerates src/market/instruments.ts from NSE's official NIFTY 500 and NIFTY 50 constituent lists.
// Run after NSE rebalances its indices: npm run update-instruments --workspace @xocrisk/api
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const userAgent = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0 Safari/537.36";

async function constituents(list: string): Promise<{ name: string; industry: string; symbol: string }[]> {
  const response = await fetch(`https://nsearchives.nseindia.com/content/indices/ind_${list}list.csv`, {
    headers: { "User-Agent": userAgent },
  });
  if (!response.ok) throw new Error(`NSE returned ${response.status} for ${list}`);
  const [, ...rows] = (await response.text()).trim().split(/\r?\n/);
  return rows.map((row) => {
    // Company Name,Industry,Symbol,Series,ISIN Code (names never contain commas in these files)
    const [name = "", industry = "", symbol = ""] = row.split(",");
    return { name: name.trim(), industry: industry.trim(), symbol: symbol.trim() };
  }).filter((row) => row.symbol);
}

const [nifty500, nifty50] = await Promise.all([constituents("nifty500"), constituents("nifty50")]);
const inNifty50 = new Set(nifty50.map((row) => row.symbol));
const sorted = [...nifty500].sort((a, b) =>
  Number(inNifty50.has(b.symbol)) - Number(inNifty50.has(a.symbol)) || a.symbol.localeCompare(b.symbol));

const output = `// Generated by scripts/update-instruments.ts from NSE's NIFTY 500 list on ${new Date().toISOString().slice(0, 10)}.
// NIFTY 50 stocks come first. Do not edit by hand; rerun the script instead.
export type Instrument = { symbol: string; name: string; industry: string; nifty50: boolean };

export const instruments: Instrument[] = [
${sorted.map((row) => `  ${JSON.stringify({ symbol: row.symbol, name: row.name, industry: row.industry, nifty50: inNifty50.has(row.symbol) })},`).join("\n")}
];
`;
await writeFile(resolve(process.cwd(), "src/market/instruments.ts"), output);
console.log(`Wrote ${sorted.length} instruments (${nifty50.length} in NIFTY 50).`);
