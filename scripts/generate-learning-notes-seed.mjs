// Reproduce the initial seed from the installed library. Never copies personal user notes.
import { readFile, writeFile } from 'node:fs/promises';
const library = JSON.parse(await readFile(new URL('../frontend/src/components/market-pattern-library/patterns.json', import.meta.url), 'utf8'));
const bullets = values => values.map(value => `• ${value}`).join('\n');
const section = (title, value) => `${title}\n${Array.isArray(value) ? bullets(value) : value}`;
const notes = [
  ...library.lessons.map((lesson, index) => ({
    id: `lesson-${lesson.id}`, title: lesson.title, body: `${lesson.body}\n\n${bullets(lesson.points)}`,
    category: 'foundation', illustrations: [], sortOrder: index,
  })),
  ...library.patterns.map((pattern, index) => ({
    id: pattern.id, title: pattern.name, category: pattern.category, illustrations: pattern.illustrations, sortOrder: 100 + index,
    body: [
      pattern.overview,
      section('Interpretation', `${pattern.type} · ${pattern.bias}`),
      section('Context', pattern.context), section('Recognition', pattern.recognition),
      section('Confirmation to study', pattern.confirmation), section('What weakens the scenario', pattern.invalidation),
      section('Target framework', pattern.targetMethod), section('Common mistakes and limitations', pattern.cautions),
      pattern.aliases.length ? section('Also called', pattern.aliases) : '',
      pattern.variants.length ? section('Variants', pattern.variants) : '',
      section('Timeframe', pattern.timeframeNote), pattern.reliability.status,
    ].filter(Boolean).join('\n\n'),
  })),
];
const quote = value => `'${String(value).replaceAll("'", "''")}'`;
for (const note of notes) {
  if (note.title.length > 120 || note.body.length > 10000) throw new Error(`Note too long: ${note.id}`);
}
const values = notes.map(note => `(${[note.id, note.title, note.body, note.category, JSON.stringify(note.illustrations)].map(quote).join(', ')}, ${note.sortOrder})`);
await writeFile(new URL('../backend/migrations/020_seed_learning_notes.sql', import.meta.url),
  '-- Generated by scripts/generate-learning-notes-seed.mjs; 7 foundations and 53 patterns.\n'
  + 'INSERT INTO learning_notes (id, title, body, category, illustrations, sort_order) VALUES\n'
  + values.join(',\n') + '\nON CONFLICT (id) DO NOTHING;\n');
console.log(`Prepared ${notes.length} shared learning notes.`);
